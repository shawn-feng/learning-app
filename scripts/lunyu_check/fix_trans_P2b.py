count = 0
for name, reps in fixes.items():
    for ext in ['.md', '.html']:
        p = os.path.join(MAT, name + ext)
        if not os.path.exists(p):
            continue
        with io.open(p, encoding='utf-8') as f:
            t = f.read()
        orig = t
        for old, new in reps:
            if old in t:
                t = t.replace(old, new)
            else:
                print(f'  {name}{ext}: 未找到 "{old[:25]}"')
        if t != orig:
            with io.open(p, 'w', encoding='utf-8') as f:
                f.write(t)
            count += 1
            print(f'✓ {name}{ext}')

print(f'\n共修正 {count} 个文件')
